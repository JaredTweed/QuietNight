#!/usr/bin/env python3
"""Generate the offline Kotlin lookup from pinned public-domain IANA tzdb tables."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/tzdb/2026e'
OUTPUT = ROOT / 'android/app/src/main/java/dev/jaredtweed/quietnight/sleep/TimeZoneCities.kt'


def degrees(value, digits):
    sign = -1 if value[0] == '-' else 1
    value = value[1:]
    return sign * (int(value[:digits]) + int(value[digits:digits + 2]) / 60
                   + (int(value[digits + 2:]) / 3600 if len(value) > digits + 2 else 0))


def generate():
    points = {}
    # Keep named cities in zone.tab even when their modern clock rules share a zone1970 entry.
    for filename in ('zone1970.tab', 'zone.tab'):
        for line in (SOURCE / filename).read_text().splitlines():
            if not line or line.startswith('#'):
                continue
            _, coordinate, zone, *_ = line.split()
            match = re.fullmatch(r'([+-]\d{4}(?:\d{2})?)([+-]\d{5}(?:\d{2})?)', coordinate)
            if not match:
                raise ValueError(coordinate)
            points[zone] = (degrees(match[1], 2), degrees(match[2], 3))
    aliases = {}
    for line in (SOURCE / 'backward').read_text().splitlines():
        fields = line.split()
        if fields and fields[0] == 'Link':
            aliases[fields[2]] = fields[1]
    for name in aliases:
        visited = set()
        while name in aliases and name not in points:
            if name in visited:
                raise ValueError('Cyclic alias')
            visited.add(name)
            name = aliases[name]
    coordinates = '\n'.join(f'{zone}\t{lat:.8f}\t{lon:.8f}' for zone, (lat, lon) in sorted(points.items()))
    links = '\n'.join(f'{alias}\t{target}' for alias, target in sorted(aliases.items()))
    # Each Kotlin/JVM string constant must fit the class-file UTF-8 limit.
    assert max(len(coordinates.encode()), len(links.encode())) < 60000
    return '''package dev.jaredtweed.quietnight.sleep

import java.time.ZoneId

/** Generated by tools/generate_time_zone_cities.py from public-domain IANA tzdb 2026e.
 * Reference cities estimate solar times; these coordinates are never device location.
 */
internal object TimeZoneCities {
    data class City(val zoneId: String, val latitude: Double, val longitude: Double) {
        val name: String get() = zoneId.substringAfterLast('/').replace('_', ' ')
    }

    private val cities by lazy {
        coordinates.lineSequence().associate { line ->
            val fields = line.split('\\t')
            fields[0] to City(fields[0], fields[1].toDouble(), fields[2].toDouble())
        }
    }
    private val links by lazy {
        aliases.lineSequence().associate { line ->
            val fields = line.split('\\t')
            fields[0] to fields[1]
        }
    }

    fun find(zone: ZoneId): City? {
        var id = zone.id
        val visited = mutableSetOf<String>()
        while (visited.add(id)) {
            cities[id]?.let { return it }
            id = links[id] ?: return null
        }
        return null
    }

    private val coordinates = """
''' + coordinates + '''
""".trim()
    private val aliases = """
''' + links + '''
""".trim()
}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if OUTPUT.read_text() != result:
            raise SystemExit('TimeZoneCities.kt is out of date')
        print('Offline time-zone city lookup matches pinned tzdb source')
    else:
        OUTPUT.write_text(result)
        print('Generated', OUTPUT.relative_to(ROOT))
